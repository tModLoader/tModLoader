namespace Terraria.ID;

/// <summary>
/// The categories on the main Journey Mode power strip. Categories added with <see cref="ModLoader.ModCreativeCategory"/> use IDs from <see cref="Count"/> upwards.
/// </summary>
public static class CreativeCategoryID
{
	public const int None = 0;
	public const int Duplication = 1;
	public const int Research = 2;
	public const int Time = 3;
	public const int Weather = 4;
	public const int Difficulty = 5;
	public const int Personal = 6;
	public static readonly int Count = 7;
}
