using System;
using System.Collections.Generic;
using Terraria.GameContent.ChestLootRules;

namespace Terraria.ModLoader;

/// <summary> Provides access to rules for one chest type, resolved by <see cref="ChestLootDatabase"/> in registration order. </summary>
public readonly struct ChestLoot
{
	private readonly int chestID;

	internal ChestLoot(int chestID)
	{
		this.chestID = chestID;
	}

	/// <summary> Gets a copy of the list of registered <see cref="IChestLootRule"/> instances. </summary>
	public List<IChestLootRule> Get() => ChestLootDatabase.GetRules(chestID);

	/// <summary> Creates <see cref="CommonChestDropRule"/>, with a chance and stack range. </summary>
	public static IChestLootRule Common(int itemType, int chanceDenominator = 1, int stackMin = 1, int stackMax = 1, int chanceNumerator = 1)
		=> new CommonChestDropRule(itemType, chanceDenominator, stackMin, stackMax, chanceNumerator);

	/// <summary> Creates <see cref="OneFromOptionsChestDropRule"/>, that selects one item from the options. </summary>
	public static IChestLootRule OneFromOptions(int chanceDenominator, params int[] itemTypes)
		=> new OneFromOptionsChestDropRule(chanceDenominator, itemTypes);

	/// <summary> Creates <see cref="OneFromOptionsChestDropRule"/>, with a configurable chance numerator and denominator. </summary>
	public static IChestLootRule OneFromOptionsWithChance(int chanceDenominator, int chanceNumerator, params int[] itemTypes)
		=> new OneFromOptionsChestDropRule(chanceDenominator, chanceNumerator, itemTypes);

	/// <summary> Creates <see cref="ConditionalChestLootRule"/>. All conditions must be met and are evaluated when the rule runs. </summary>
	public static IChestLootRule ByCondition(IChestLootCondition condition, IChestLootRule rule)
		=> new ConditionalChestLootRule(condition, rule);

	/// <summary> Registers and returns the rule instance. Rules run in registration order. </summary>
	public IChestLootRule Add(IChestLootRule rule) => ChestLootDatabase.Register(chestID, rule);

	/// <summary> Creates and registers <see cref="ConditionalChestLootRule"/>. Conditions are evaluated when the rule runs. </summary>
	public IChestLootRule AddByCondition(IChestLootCondition condition, IChestLootRule rule)
		=> Add(ByCondition(condition, rule));

	/// <summary> Registers <see cref="CommonChestDropRule"/>. </summary>
	public IChestLootRule AddCommon(int itemType, int chanceDenominator = 1, int stackMin = 1, int stackMax = 1, int chanceNumerator = 1)
		=> Add(Common(itemType, chanceDenominator, stackMin, stackMax, chanceNumerator));

	/// <summary> Registers <see cref="OneFromOptionsChestDropRule"/>. </summary>
	public IChestLootRule AddOneFromOptions(int chanceDenominator, params int[] itemTypes)
		=> Add(OneFromOptions(chanceDenominator, itemTypes));

	/// <summary> Registers a chance-based <see cref="OneFromOptionsChestDropRule"/>. </summary>
	public IChestLootRule AddOneFromOptionsWithChance(int chanceDenominator, int chanceNumerator, params int[] itemTypes)
		=> Add(OneFromOptionsWithChance(chanceDenominator, chanceNumerator, itemTypes));

	/// <summary> Registers an item replacement rule that replaces every matching stack in the chest. </summary>
	public IChestLootRule ReplaceItem(int oldItemType, int newItemType)
		=> Add(new ReplaceChestItemRule(oldItemType, newItemType));

	/// <summary> Registers an item removal rule that removes up to the specified amount. </summary>
	public IChestLootRule RemoveItem(int itemType, int stack = int.MaxValue)
		=> Add(new RemoveChestItemRule(itemType, stack));

	/// <summary> Registers a rule that clears vanilla loot and items generated by preceding rules. </summary>
	public IChestLootRule ClearChestContents()
		=> Add(new ClearChestContentsRule());

	/// <summary> Removes a registered rule instance. Pass the original instance retrieved from <see cref="Get"/>. </summary>
	public IChestLootRule Remove(IChestLootRule rule) => ChestLootDatabase.Remove(chestID, rule);

	/// <summary> Removes all registered rules matching the predicate. </summary>
	public void RemoveWhere(Predicate<IChestLootRule> predicate)
	{
		if (predicate == null)
			throw new ArgumentNullException(nameof(predicate));

		foreach (IChestLootRule rule in Get()) {
			if (predicate(rule))
				Remove(rule);
		}
	}

	/// <summary> Creates <see cref="ConditionalChestLootRule"/>. All conditions must be met and are evaluated when the rule runs. </summary>
	public static IChestLootRule ByCondition(Condition condition, IChestLootRule rule) => ByCondition(new ChestLootCondition(condition), rule);
	/// <summary> Creates and registers <see cref="ConditionalChestLootRule"/>. Conditions are evaluated when the rule runs. </summary>
	public IChestLootRule AddByCondition(Condition condition, IChestLootRule rule) => Add(ByCondition(condition, rule));
	/// <summary> Creates <see cref="ConditionalChestLootRule"/>. All conditions must be met and are evaluated when the rule runs. </summary>
	public static IChestLootRule ByCondition(IChestLootRule rule, params IChestLootCondition[] conditions) => new ConditionalChestLootRule(rule, conditions);
	/// <summary> Creates and registers <see cref="ConditionalChestLootRule"/>. Conditions are evaluated when the rule runs. </summary>
	public IChestLootRule AddByCondition(IChestLootRule rule, params IChestLootCondition[] conditions) => Add(ByCondition(rule, conditions));
	/// <summary> Creates <see cref="ConditionalChestLootRule"/>. All conditions must be met and are evaluated when the rule runs. </summary>
	public static IChestLootRule ByCondition(IChestLootCondition condition, int itemType, int chanceDenominator = 1, int stackMin = 1, int stackMax = 1, int chanceNumerator = 1) => ByCondition(condition, Common(itemType, chanceDenominator, stackMin, stackMax, chanceNumerator));
	/// <summary> Creates and registers <see cref="ConditionalChestLootRule"/>. Conditions are evaluated when the rule runs. </summary>
	public IChestLootRule AddByCondition(IChestLootCondition condition, int itemType, int chanceDenominator = 1, int stackMin = 1, int stackMax = 1, int chanceNumerator = 1) => Add(ByCondition(condition, itemType, chanceDenominator, stackMin, stackMax, chanceNumerator));
}